# Builds anti-aliased glyph atlases (8-bit coverage) from Inter (SIL Open Font License)
# for the DuncOS user interface. Output: common/uifont_data.h
from PIL import Image, ImageDraw, ImageFont
D = "/usr/share/fonts/opentype/inter/"
FONTS = [("ui", "Inter-Regular.otf", 14), ("ui_bold", "Inter-SemiBold.otf", 14),
         ("title", "Inter-SemiBold.otf", 20), ("big", "Inter-Light.otf", 34)]
out = ["/* Generated by tools/genuifont.py from Inter (SIL Open Font License 1.1). */", "#pragma once"]
for name, file, size in FONTS:
    f = ImageFont.truetype(D + file, size)
    asc, desc = f.getmetrics()
    bits, glyphs = [], []
    for c in range(32, 256):                                  # Windows-1252, the DuncOS text encoding
        try: ch = bytes([c]).decode("cp1252")
        except UnicodeDecodeError: ch = "?"
        if c in (127, 160): ch = " "
        adv = int(round(f.getlength(ch)))
        if ch == " ":
            glyphs.append((0, 0, 0, 0, adv, len(bits))); continue
        x0, y0, x1, y1 = f.getbbox(ch, anchor="ls")
        w, h = x1 - x0, y1 - y0
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-x0, -y0), ch, font=f, fill=255, anchor="ls")
        glyphs.append((x0, y0, w, h, adv, len(bits)))
        bits += list(img.getdata())
    out.append("static const uint8_t %s_bits[%d] = {" % (name, len(bits)))
    for i in range(0, len(bits), 32):
        out.append("  " + ",".join(str(b) for b in bits[i:i+32]) + ",")
    out.append("};")
    out.append("static const struct glyph %s_glyphs[224] = {" % name)
    for g in glyphs:
        out.append("  {%d,%d,%d,%d,%d,%d}," % g)
    out.append("};")
    out.append("const struct font font_%s = { %d, %d, %d, %s_glyphs, %s_bits };" % (name, size, asc, desc, name, name))
open("common/uifont_data.h", "w").write("\n".join(out) + "\n")
