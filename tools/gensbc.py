#!/usr/bin/env python3
# Makes src/sbc_tables.h: the SBC analysis window (8 subbands) and cosine matrix, from the prototype filter's
# 80 magnitudes in tools/sbc_proto8.txt (SBC specification). The prototype is a symmetric low-pass filter whose
# sign changes between taps 12/13 and 26/27 (and the mirror image); each 16-tap group is then given the
# alternating sign that folding 80 taps into 16 needs.
import math, os
here = os.path.dirname(os.path.abspath(__file__))
mag = [float(x) for x in open(os.path.join(here, 'sbc_proto8.txt')).read().split()]
def hs(i): return 1 if (i <= 12 or 27 <= i <= 53 or i >= 68) else -1
cq = [round(mag[i] * hs(i) * (-1) ** (i // 16) * (1 << 30)) for i in range(80)]
M = [[round(math.cos((k + 0.5) * (i - 4) * math.pi / 8) * (1 << 14)) for i in range(16)] for k in range(8)]
with open(os.path.join(here, '..', 'src', 'sbc_tables.h'), 'w') as f:
    f.write("/* SBC encoder tables (8 subbands): the analysis window from the SBC specification's prototype filter, with\n * the alternating sign of each 16-tap group folded in, as Q30; and the analysis cosine matrix\n * cos((k + 1/2)(i - 4) pi / 8) as Q14. Generated by tools/gensbc.py. */\n#pragma once\n#include <stdint.h>\n")
    f.write('static const int32_t sbc_win8[80] = {\n' + ',\n'.join('    ' + ', '.join(str(v) for v in cq[i:i + 8]) for i in range(0, 80, 8)) + '\n};\n')
    f.write('static const int16_t sbc_cos8[8][16] = {\n' + ',\n'.join('    { ' + ', '.join(str(v) for v in r) + ' }' for r in M) + '\n};\n')
