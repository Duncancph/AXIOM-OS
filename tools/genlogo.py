# AXIOM logo: the traced outline (tools/axiom_logo_raw.json, traced from the artwork) tidied up, then rendered
# as anti-aliased alpha maps at the sizes the system uses -> common/logo_data.h
import json, sys
from PIL import Image, ImageDraw, ImageFilter
L = json.load(open("tools/axiom_logo_raw.json"))
shapes = L["shapes"]

def snap(vals, tol):                       # pull nearly equal coordinates to one value (baselines, cap height, stems)
    vals = sorted(set(vals)); groups = []
    for v in vals:
        if groups and v - groups[-1][-1] <= tol: groups[-1].append(v)
        else: groups.append([v])
    return {v: sum(g) / len(g) for g in groups for v in g}
ys = snap([p[1] for s in shapes for p in s["pts"]], 1.2)
xs = snap([p[0] for s in shapes for p in s["pts"]], 0.6)
for s in shapes:
    if len(s["pts"]) > 20: continue        # the O: keep its curve as traced
    s["pts"] = [[xs[p[0]], ys[p[1]]] for p in s["pts"]]
W, H = L["w"], L["h"]
mark_w = max(p[0] for s in shapes for p in s["pts"] if p[0] < 130) + 0.5   # the mark is the left part
def render(scale_h, part="all", pad=0, blur=0, SS=8):
    k = scale_h / H
    x1 = mark_w if part == "mark" else W
    w, h = int(x1 * k + 0.999) + 2 * pad, int(H * k + 0.999) + 2 * pad
    img = Image.new("L", (w * SS, h * SS), 0); d = ImageDraw.Draw(img)
    for s in sorted(shapes, key=lambda s: s["hole"]):
        if part == "mark" and min(p[0] for p in s["pts"]) > mark_w: continue
        d.polygon([((pad + p[0] * k) * SS, (pad + p[1] * k) * SS) for p in s["pts"]], fill=0 if s["hole"] else 255)
    img = img.resize((w, h), Image.LANCZOS)
    if blur: img = img.filter(ImageFilter.GaussianBlur(blur))
    return img
out = ["/* Generated by tools/genlogo.py: the AXIOM logo as 8-bit alpha maps. */", "#pragma once", "#include <stdint.h>",
       "#ifndef LOGO_IMG_DEFINED", "#define LOGO_IMG_DEFINED", "struct logo_img { int w, h; const uint8_t *a; };", "#endif"]
items = [("logo_bar", 18, "all", 0, 0), ("logo_mark_term", 56, "mark", 0, 0), ("logo_mark_bar", 18, "mark", 0, 0), ("logo_mid", 40, "all", 0, 0),
         ("logo_splash", 64, "all", 0, 0), ("logo_mark_big", 120, "mark", 0, 0), ("logo_glow", 300, "mark", 80, 16)]
prev = []
for name, hh, part, pad, blur in items:
    im = render(hh, part, pad, blur); prev.append(im)
    px = list(im.tobytes())
    out.append("static const uint8_t %s_a[%d] = {" % (name, len(px)))
    for i in range(0, len(px), 32): out.append("  " + ",".join(str(v) for v in px[i:i + 32]) + ",")
    out.append("};")
    out.append("static const struct logo_img %s = { %d, %d, %s_a };" % (name, im.width, im.height, name))
open("common/logo_data.h", "w").write("\n".join(out) + "\n")
if len(sys.argv) > 2 and sys.argv[1] == "--preview":
    sheet = Image.new("RGB", (900, 700), (0, 0, 0)); y = 10
    for im in prev:
        col = Image.new("RGB", im.size, (244, 241, 222)); sheet.paste(col, (10, y), im); y += im.height + 10
    sheet.save(sys.argv[2])
