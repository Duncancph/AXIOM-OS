# Generates src/keymaps.h: keyboard layouts as tables indexed by USB HID usage code.
# Characters are Windows-1252 (the AXIOM text encoding). Dead keys are DEAD_BASE + accent number.
import unicodedata
USAGES = list(range(0x04, 0x28)) + list(range(0x2D, 0x39)) + [0x64]     # letters, digits, punctuation, ISO extra key
ACCENTS = ["\u0300", "\u0301", "\u0302", "\u0308", "\u0303"]          # grave, acute, circumflex, diaeresis, tilde
ACCENT_CHARS = ["`", "\u00b4", "^", "\u00a8", "~"]                    # what the dead key types on its own
DEAD = {"dead_grave": 0, "dead_acute": 1, "dead_circumflex": 2, "dead_diaeresis": 3, "dead_tilde": 4}
DEAD_BASE = 0x300

US_LO = "abcdefghijklmnopqrstuvwxyz1234567890-=[]\\\\;'`,./\\"
US_HI = "ABCDEFGHIJKLMNOPQRSTUVWXYZ!@#$%^&*()_+{}||:\"~<>?|"

def table(lo, hi, altgr=None):
    """lo/hi: lists of 49 entries (str of length 1, or a dead-key name); altgr: dict usage -> entry"""
    altgr = altgr or {}
    return [(lo[i], hi[i], altgr.get(u, "")) for i, u in enumerate(USAGES)]

def L(s): return list(s)

def with_(base, changes):
    out = list(base)
    for u, v in changes.items(): out[USAGES.index(u)] = v
    return out

layouts = {}
layouts["us"] = ("English (US)", table(L(US_LO), L(US_HI)))

uk_lo = with_(L(US_LO), {0x31: "#", 0x32: "#", 0x64: "\\"})
uk_hi = with_(L(US_HI), {0x1F: "\"", 0x20: "\u00a3", 0x34: "@", 0x35: "\u00ac", 0x31: "~", 0x32: "~", 0x64: "|"})
layouts["uk"] = ("English (UK)", table(uk_lo, uk_hi, {0x21: "\u20ac", 0x35: "\u00a6", 0x04: "\u00e1", 0x08: "\u00e9", 0x0C: "\u00ed", 0x12: "\u00f3", 0x18: "\u00fa"}))

de_lo = with_(L(US_LO), {0x1C: "z", 0x1D: "y", 0x2D: "\u00df", 0x2E: "dead_acute", 0x2F: "\u00fc", 0x30: "+", 0x31: "#", 0x32: "#",
                         0x33: "\u00f6", 0x34: "\u00e4", 0x35: "dead_circumflex", 0x36: ",", 0x37: ".", 0x38: "-", 0x64: "<"})
de_hi = with_(L(US_HI), {0x1C: "Z", 0x1D: "Y", 0x1F: "\"", 0x20: "\u00a7", 0x23: "&", 0x24: "/", 0x25: "(", 0x26: ")", 0x27: "=", 0x2D: "?",
                         0x2E: "dead_grave", 0x2F: "\u00dc", 0x30: "*", 0x31: "'", 0x32: "'", 0x33: "\u00d6", 0x34: "\u00c4", 0x35: "\u00b0",
                         0x36: ";", 0x37: ":", 0x38: "_", 0x64: ">"})
layouts["de"] = ("Deutsch", table(de_lo, de_hi, {0x14: "@", 0x08: "\u20ac", 0x1F: "\u00b2", 0x20: "\u00b3", 0x24: "{", 0x25: "[", 0x26: "]",
                                                 0x27: "}", 0x2D: "\\", 0x30: "~", 0x64: "|", 0x10: "\u00b5"}))

fr_lo = with_(L(US_LO), {0x04: "q", 0x14: "a", 0x1A: "z", 0x1D: "w", 0x10: ",", 0x33: "m",
                         0x1E: "&", 0x1F: "\u00e9", 0x20: "\"", 0x21: "'", 0x22: "(", 0x23: "-", 0x24: "\u00e8", 0x25: "_", 0x26: "\u00e7", 0x27: "\u00e0",
                         0x2D: ")", 0x2E: "=", 0x2F: "dead_circumflex", 0x30: "$", 0x31: "*", 0x32: "*", 0x34: "\u00f9", 0x35: "\u00b2",
                         0x36: ";", 0x37: ":", 0x38: "!", 0x64: "<"})
fr_hi = with_(L(US_HI), {0x04: "Q", 0x14: "A", 0x1A: "Z", 0x1D: "W", 0x10: "?", 0x33: "M",
                         0x1E: "1", 0x1F: "2", 0x20: "3", 0x21: "4", 0x22: "5", 0x23: "6", 0x24: "7", 0x25: "8", 0x26: "9", 0x27: "0",
                         0x2D: "\u00b0", 0x2E: "+", 0x2F: "dead_diaeresis", 0x30: "\u00a3", 0x31: "\u00b5", 0x32: "\u00b5", 0x34: "%", 0x35: "\u00b2",
                         0x36: ".", 0x37: "/", 0x38: "\u00a7", 0x64: ">"})
layouts["fr"] = ("Fran\u00e7ais", table(fr_lo, fr_hi, {0x1F: "dead_tilde", 0x20: "#", 0x21: "{", 0x22: "[", 0x23: "|", 0x24: "dead_grave", 0x25: "\\",
                                                       0x26: "^", 0x27: "@", 0x2D: "]", 0x2E: "}", 0x08: "\u20ac", 0x30: "\u00a4"}))

es_lo = with_(L(US_LO), {0x2D: "'", 0x2E: "\u00a1", 0x2F: "dead_grave", 0x30: "+", 0x31: "\u00e7", 0x32: "\u00e7", 0x33: "\u00f1",
                         0x34: "dead_acute", 0x35: "\u00ba", 0x36: ",", 0x37: ".", 0x38: "-", 0x64: "<"})
es_hi = with_(L(US_HI), {0x1F: "\"", 0x20: "\u00b7", 0x23: "&", 0x24: "/", 0x25: "(", 0x26: ")", 0x27: "=", 0x2D: "?", 0x2E: "\u00bf",
                         0x2F: "dead_circumflex", 0x30: "*", 0x31: "\u00c7", 0x32: "\u00c7", 0x33: "\u00d1", 0x34: "dead_diaeresis", 0x35: "\u00aa",
                         0x36: ";", 0x37: ":", 0x38: "_", 0x64: ">"})
layouts["es"] = ("Espa\u00f1ol", table(es_lo, es_hi, {0x1E: "|", 0x1F: "@", 0x20: "#", 0x21: "~", 0x23: "\u00ac", 0x08: "\u20ac", 0x2F: "[", 0x30: "]",
                                                     0x31: "}", 0x32: "}", 0x34: "{", 0x35: "\\"}))

def code(v):
    if not v: return 0
    if v in DEAD: return DEAD_BASE + DEAD[v]
    b = v.encode("cp1252")
    assert len(b) == 1, v
    return b[0]

out = ["/* Generated by tools/genkeymaps.py. Keyboard layouts by USB HID usage; Windows-1252 characters; */",
       "/* values >= KM_DEAD are dead keys (accent number = value - KM_DEAD: grave, acute, circumflex, diaeresis, tilde). */",
       "#pragma once", "#include <stdint.h>", "#define KM_DEAD 0x%X" % DEAD_BASE, "#define KM_KEYS %d" % len(USAGES),
       "static const uint8_t km_usages[KM_KEYS] = { " + ", ".join("0x%02X" % u for u in USAGES) + " };",
       "struct keymap { const char *id, *name; uint16_t key[KM_KEYS][3]; };",
       "static const struct keymap keymaps[] = {"]
for lid, (name, t) in layouts.items():
    assert len(t) == len(USAGES), lid
    out.append('  { "%s", "%s", {' % (lid, "".join(c if ord(c) < 128 else "\\x%02x\" \"" % c.encode("cp1252")[0] for c in name)))
    out.append("    " + ", ".join("{%d,%d,%d}" % (code(a), code(b), code(c)) for a, b, c in t))
    out.append("  } },")
out.append("};")
out.append("#define KM_COUNT %d" % len(layouts))
# accent composition: (accent, base char) -> cp1252 char
comp = []
for ai, acc in enumerate(ACCENTS):
    for base in "aeiouyncAEIOUYNC ":
        if base == " ": r = ACCENT_CHARS[ai]
        else: r = unicodedata.normalize("NFC", base + acc)
        try: b = r.encode("cp1252")
        except UnicodeEncodeError: continue
        if len(b) == 1 and (base == " " or len(r) == 1): comp.append((ai, ord(base), b[0]))
out.append("static const uint8_t km_compose[][3] = { " + ", ".join("{%d,%d,%d}" % c for c in comp) + " };")
out.append("#define KM_NCOMPOSE %d" % len(comp))
open("src/keymaps.h", "w").write("\n".join(out) + "\n")
print("layouts:", ", ".join(layouts), "| compositions:", len(comp))
