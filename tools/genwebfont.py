# Builds the anti-aliased glyph atlases (8-bit coverage) the Web browser uses for page text,
# from Inter (SIL Open Font License), in the same format as tools/genuifont.py.
# Output: common/webfont_data.h (included only by the Web app).
from PIL import Image, ImageDraw, ImageFont
D = "/usr/share/fonts/opentype/inter/"
SIZES = [12, 14, 16, 18, 22, 28, 36]
STYLES = [("r", "Inter-Regular.otf", SIZES), ("b", "Inter-SemiBold.otf", SIZES), ("i", "Inter-Italic.otf", [14, 16, 18])]
out = ["/* Generated by tools/genwebfont.py from Inter (SIL Open Font License 1.1). */", "#pragma once"]
table = []
for st, file, sizes in STYLES:
    for size in sizes:
        name = "wf_%s%d" % (st, size)
        f = ImageFont.truetype(D + file, size)
        asc, desc = f.getmetrics()
        bits, glyphs = [], []
        for c in range(32, 256):                              # Windows-1252, the AXIOM text encoding
            try: ch = bytes([c]).decode("cp1252")
            except UnicodeDecodeError: ch = "?"
            if c in (127, 160): ch = " "
            adv = int(round(f.getlength(ch)))
            if ch == " ":
                glyphs.append((0, 0, 0, 0, adv, len(bits))); continue
            x0, y0, x1, y1 = f.getbbox(ch, anchor="ls")
            w, h = x1 - x0, y1 - y0
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-x0, -y0), ch, font=f, fill=255, anchor="ls")
            glyphs.append((x0, y0, w, h, adv, len(bits)))
            bits += list(img.tobytes())
        out.append("static const uint8_t %s_bits[%d] = {" % (name, len(bits)))
        for i in range(0, len(bits), 40):
            out.append(",".join(str(b) for b in bits[i:i+40]) + ",")
        out.append("};")
        out.append("static const struct glyph %s_glyphs[224] = {" % name)
        for i in range(0, 224, 8):
            out.append(" ".join("{%d,%d,%d,%d,%d,%d}," % g for g in glyphs[i:i+8]))
        out.append("};")
        out.append("static const struct font %s = { %d, %d, %d, %s_glyphs, %s_bits };" % (name, size, asc, desc, name, name))
        table.append((st, size, name))
for st in ("r", "b", "i"):
    ent = [t for t in table if t[0] == st]
    out.append("static const struct font *const wf_%s_set[%d] = { %s };" % (st, len(ent), ", ".join("&" + t[2] for t in ent)))
    out.append("static const int wf_%s_sizes[%d] = { %s };" % (st, len(ent), ", ".join(str(t[1]) for t in ent)))
open("common/webfont_data.h", "w").write("\n".join(out) + "\n")
