# Turns a text file into a C header with one string constant: embed.py <input> <output> <name>
import sys
src = open(sys.argv[1], encoding="utf-8").read()
out = ["/* Generated by tools/embed.py from %s */" % sys.argv[1], "static const char %s[] =" % sys.argv[3]]
for line in src.split("\n"):
    esc = line.replace("\\", "\\\\").replace('"', '\\"').replace("??", "?\\?")
    out.append('  "%s\\n"' % esc)
out.append(";")
open(sys.argv[2], "w").write("\n".join(out) + "\n")
