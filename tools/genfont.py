# Rasterizes DejaVu Sans Mono (permissive Bitstream Vera license) into an 8x16 bitmap font.
import sys
from PIL import Image, ImageDraw, ImageFont
path = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
font = ImageFont.truetype(path, 13)
out = ["/* Generated by tools/genfont.py from DejaVu Sans Mono. 8x16, ASCII 0-127. */",
       "#pragma once", "static const unsigned char font8x16[128*16] = {"]
asc, desc = font.getmetrics()
for c in range(128):
    rows = [0]*16
    if 32 < c < 127:
        img = Image.new("L", (8, 16), 0)
        d = ImageDraw.Draw(img)
        d.text((0, 12 - asc), chr(c), font=font, fill=255)
        for y in range(16):
            b = 0
            for x in range(8):
                if img.getpixel((x, y)) > 100: b |= 0x80 >> x
            rows[y] = b
    out.append("  " + ",".join("0x%02x" % r for r in rows) + ",  /* %d */" % c)
out.append("};")
open(sys.argv[2] if len(sys.argv) > 2 else "src/font.h", "w").write("\n".join(out) + "\n")
